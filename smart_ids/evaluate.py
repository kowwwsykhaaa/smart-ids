"""Measure the rule detector and the Isolation Forest on synthetic labeled traffic.

Run:  python -m smart_ids.evaluate
Writes results.md with the numbers (nothing is hard-coded).

How it is scored
- Ground truth: attack episodes (known source IP, start, end).
- An episode is DETECTED if the detector raises an alert for that source IP
  during the episode (within one 10 s window of it).
- An alert is TRUE if it is for an attacker source during an episode; otherwise
  it is a FALSE ALARM (every benign source is harmless by construction).
"""
import sys
from collections import defaultdict
from pathlib import Path

import joblib

from .detector import RuleDetector
from .ml import AnomalyModel, WINDOW, group_windows
from .traffic_sim import generate, ATTACK_KINDS

SLACK = WINDOW


def rule_alerts(pkts):
    det, out = RuleDetector(), []
    for p in pkts:
        out += det.process(p)
    return [(a.ip, a.ts) for a in out]


def ml_alerts(model, pkts):
    flagged = model.predict_windows(pkts)
    return [(src, (idx + 0.5) * WINDOW) for (src, idx), bad in flagged.items() if bad]


def score(alerts, episodes):
    """alerts: list of (src, ts). Returns dict of metrics."""
    by_src = defaultdict(list)
    for e in episodes:
        by_src[e["src"]].append(e)

    def is_true(src, ts):
        return any(e["start"] - SLACK <= ts <= e["end"] + SLACK for e in by_src.get(src, []))

    true_alerts = sum(is_true(s, t) for s, t in alerts)
    false_alerts = len(alerts) - true_alerts
    detected = defaultdict(lambda: [0, 0])          # kind -> [detected, total]
    for e in episodes:
        detected[e["kind"]][1] += 1
        if any(s == e["src"] and e["start"] - SLACK <= t <= e["end"] + SLACK for s, t in alerts):
            detected[e["kind"]][0] += 1
    det_total = sum(v[0] for v in detected.values())
    ep_total = sum(v[1] for v in detected.values())
    recall = det_total / ep_total if ep_total else 0.0
    precision = true_alerts / len(alerts) if alerts else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return dict(detected=detected, recall=recall, precision=precision, f1=f1,
                false_alerts=false_alerts, alerts=len(alerts))


def run(train_seed=1, test_seed=2, episodes=80, quiet=False):
    train_pkts, _ = generate(train_seed, duration=3600, n_episodes=0)
    model = AnomalyModel()
    n_train = model.fit(train_pkts)
    test_pkts, eps = generate(test_seed, duration=3600, n_episodes=episodes)
    n_benign_windows = sum(1 for (s, _) in group_windows(test_pkts) if s.startswith("10."))

    rules = rule_alerts(test_pkts)
    ml = ml_alerts(model, test_pkts)
    results = {"Rules only": score(rules, eps),
               "Isolation Forest only": score(ml, eps),
               "Rules + Isolation Forest": score(rules + ml, eps)}
    meta = dict(n_train=n_train, n_packets=len(test_pkts), episodes=len(eps),
                n_benign_windows=n_benign_windows)
    return model, results, meta


def to_markdown(results, meta):
    L = ["# Evaluation results (synthetic traffic)", "",
         "Generated by `python -m smart_ids.evaluate`. **Synthetic data only**: "
         "these numbers describe behaviour on the traffic shapes in `traffic_sim.py`, "
         "not real networks.", "",
         f"- Training: Isolation Forest fit on {meta['n_train']} benign source-windows (10 s each)",
         f"- Test: {meta['n_packets']:,} packets, {meta['episodes']} attack episodes "
         f"({meta['episodes'] // len(ATTACK_KINDS)} per type), {meta['n_benign_windows']:,} benign source-windows", "",
         "## Overall", "",
         "| Detector | Episode recall | Alert precision | F1 | False alarms |",
         "|---|---|---|---|---|"]
    for name, r in results.items():
        L.append(f"| {name} | {r['recall']:.0%} | {r['precision']:.0%} | {r['f1']:.2f} | {r['false_alerts']} |")
    L += ["", "## Episodes detected, by attack type", "",
          "| Attack type | " + " | ".join(results) + " |", "|---|" + "---|" * len(results)]
    for kind in ATTACK_KINDS:
        row = [f"{r['detected'][kind][0]}/{r['detected'][kind][1]}" for r in results.values()]
        L.append(f"| {kind} | " + " | ".join(row) + " |")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    model, results, meta = run()
    md = to_markdown(results, meta)
    print(md)
    HERE = Path(__file__).parent
    (HERE / "results.md").write_text(md)
    joblib.dump(model, HERE / "model.joblib")
    print("saved results.md and model.joblib", file=sys.stderr)
